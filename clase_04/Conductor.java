package clase_04;
import java.util.List;

public class Conductor {
    private String nombre;
    private int edad;
    private String rut;
    private boolean habilitados;
    private List<String> licencias;

    public Conductor(String nombre, int edad, String rut, boolean habilitados, List<String> licencias) {
        this.nombre = nombre;
        this.edad = edad;
        this.rut = rut;
        this.habilitados = habilitados;
        this.licencias = licencias;
    }








}
